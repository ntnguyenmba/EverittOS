export function getTeamPageCopy(locale?: string | null): TeamPageCopy {
  const value = String(locale || 'en').toLowerCase();
  if (value.startsWith('es')) return es;
  if (value.startsWith('vi')) return asciiVi();
  return en;
}

export function teamRoleLabel(role: string, copy: TeamPageCopy) {
  const key = String(role || '').toLowerCase();
  if (key === 'owner') return copy.owner;
  if (key === 'admin') return copy.admin;
  if (key === 'manager') return copy.manager;
  if (key === 'employee' || key === 'staff') return copy.staff;
  if (key === 'contractor') return copy.contractor;
  return role;
}
